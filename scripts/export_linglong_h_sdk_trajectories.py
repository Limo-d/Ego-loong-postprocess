#!/usr/bin/env python3
"""Export a validated LingLong-H MuJoCo trajectory as SDK task CSV files."""

from __future__ import annotations

import argparse
import csv
import hashlib
import importlib.util
import json
import math
import sys
from pathlib import Path
from typing import Any

import numpy as np


ROOT = Path(__file__).resolve().parents[1]
LINGLONG_REPLAY = ROOT / "simulation/linglong_h/replay_trajectory.py"


def load_linglong_module() -> Any:
    spec = importlib.util.spec_from_file_location("linglong_h_replay_export", LINGLONG_REPLAY)
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot load {LINGLONG_REPLAY}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    module.replay.JOINT_NAMES = module.ARM_JOINT_NAMES
    return module


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def rotation_to_rpy(rotation: np.ndarray) -> np.ndarray:
    """SDK convention: R = Rz(yaw) Ry(pitch) Rx(roll)."""
    rotation = np.asarray(rotation, dtype=np.float64).reshape(3, 3)
    pitch = math.asin(float(np.clip(-rotation[2, 0], -1.0, 1.0)))
    if abs(rotation[2, 0]) < 0.999999:
        roll = math.atan2(float(rotation[2, 1]), float(rotation[2, 2]))
        yaw = math.atan2(float(rotation[1, 0]), float(rotation[0, 0]))
    else:
        roll = 0.0
        yaw = math.atan2(float(-rotation[0, 1]), float(rotation[1, 1]))
    return np.asarray([roll, pitch, yaw], dtype=np.float64)


def transform_from_body(data: Any, body_id: int) -> np.ndarray:
    transform = np.eye(4, dtype=np.float64)
    transform[:3, :3] = np.asarray(data.xmat[body_id], dtype=np.float64).reshape(3, 3)
    transform[:3, 3] = np.asarray(data.xpos[body_id], dtype=np.float64)
    return transform


def transform_from_site(data: Any, site_id: int) -> np.ndarray:
    transform = np.eye(4, dtype=np.float64)
    transform[:3, :3] = np.asarray(data.site_xmat[site_id], dtype=np.float64).reshape(3, 3)
    transform[:3, 3] = np.asarray(data.site_xpos[site_id], dtype=np.float64)
    return transform


def xyz_rpy(transform: np.ndarray) -> np.ndarray:
    return np.concatenate((transform[:3, 3], rotation_to_rpy(transform[:3, :3])))


def sample_at_sdk_rate(
    times: np.ndarray, arrays: list[np.ndarray], rate_hz: float
) -> tuple[np.ndarray, list[np.ndarray]]:
    start = float(times[0])
    stop = float(times[-1])
    sample_times = np.arange(start, stop + 0.25 / rate_hz, 1.0 / rate_hz)
    if sample_times[-1] < stop - 1e-9:
        sample_times = np.append(sample_times, stop)
    else:
        sample_times[-1] = stop
    outputs: list[np.ndarray] = []
    for values in arrays:
        flat = values.reshape(values.shape[0], -1)
        sampled = np.column_stack(
            [np.interp(sample_times, times, flat[:, column]) for column in range(flat.shape[1])]
        )
        outputs.append(sampled.reshape((sample_times.size, *values.shape[1:])))
    return sample_times, outputs


def write_csv(path: Path, comments: list[str], rows: np.ndarray) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as stream:
        for comment in comments:
            stream.write(f"# {comment}\n")
        writer = csv.writer(stream, lineterminator="\n")
        writer.writerows([[f"{float(value):.10f}" for value in row] for row in rows])


def write_yaml(path: Path, csv_format: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        "# Generated by scripts/export_linglong_h_sdk_trajectories.py\n"
        "- action: \"1\"\n"
        f"  csv_format: {csv_format}\n"
        "  speed: 1.0\n"
        "  sleep: 0.0\n",
        encoding="utf-8",
    )


def named_columns(names: np.ndarray, wanted: list[str]) -> list[int]:
    index = {str(name): position for position, name in enumerate(names.tolist())}
    missing = [name for name in wanted if name not in index]
    if missing:
        raise ValueError(f"trajectory is missing joints: {missing}")
    return [index[name] for name in wanted]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--trajectory", required=True, type=Path)
    parser.add_argument(
        "--config",
        type=Path,
        default=ROOT / "simulation/linglong_h/config_sdk_limits_candidate70.json",
    )
    parser.add_argument(
        "--output_dir",
        type=Path,
        default=ROOT / "simulation/linglong_h/sdk_exports/linglong_sdk_safe_yaw70",
    )
    parser.add_argument("--sdk_rate_hz", type=float, default=50.0)
    parser.add_argument("--initial_transition_sec", type=float, default=5.0)
    args = parser.parse_args()
    if args.sdk_rate_hz <= 0.0 or args.initial_transition_sec <= 0.0:
        parser.error("rates and initial transition must be positive")

    ll = load_linglong_module()
    config = ll.replay.load_config(args.config.resolve())
    model, data = ll.build_model(config)
    trajectory_path = args.trajectory.resolve()
    with np.load(trajectory_path) as archive:
        names = archive["joint_names"].copy()
        times = archive["times_sec"].astype(np.float64)
        qpos = archive["qpos_rad"].astype(np.float64)
        left_gripper = archive["left_gripper_position_command"].astype(np.float64)
        right_gripper = archive["right_gripper_position_command"].astype(np.float64)
        mink_clearance = archive["mink_clearance_m"].astype(np.float64)

    if qpos.shape != (times.size, names.size) or times.size < 2:
        raise ValueError("invalid trajectory dimensions")
    if np.any(np.diff(times) <= 0.0):
        raise ValueError("trajectory times must be strictly increasing")

    waist_names = list(ll.WAIST_JOINT_NAMES)
    left_names = [f"left_{name}" for name in ll.ARM_JOINT_NAMES]
    right_names = [f"right_{name}" for name in ll.ARM_JOINT_NAMES]
    controlled_names = waist_names + left_names + right_names
    controlled_columns = named_columns(names, controlled_names)

    violations: list[dict[str, Any]] = []
    margins: dict[str, float] = {}
    for joint_name, column in zip(controlled_names, controlled_columns):
        lower, upper = ll.SDK_JOINT_LIMITS_RAD[joint_name]
        values = qpos[:, column]
        margin = float(min(np.min(values - lower), np.min(upper - values)))
        margins[joint_name] = margin
        if margin < -1e-8:
            violations.append(
                {"joint": joint_name, "minimum_margin_rad": margin, "minimum": lower, "maximum": upper}
            )
    if violations:
        raise RuntimeError(f"SDK joint-limit violation: {violations}")

    sample_times, sampled = sample_at_sdk_rate(
        times,
        [qpos, left_gripper[:, None], right_gripper[:, None]],
        args.sdk_rate_hz,
    )
    sample_qpos, sample_left_gripper, sample_right_gripper = sampled
    segment_times = np.diff(sample_times, prepend=sample_times[0])
    segment_times[0] = args.initial_transition_sec

    waist_columns = named_columns(names, waist_names)
    left_columns = named_columns(names, left_names)
    right_columns = named_columns(names, right_names)
    # Simulation convention is 0=open, 1=closed; SDK cap is 1=open, 0=closed.
    caps = np.column_stack((1.0 - sample_left_gripper[:, 0], 1.0 - sample_right_gripper[:, 0]))
    caps = np.clip(caps, 0.0, 1.0)
    heads = np.zeros((sample_times.size, 2), dtype=np.float64)
    delays = np.zeros((sample_times.size, 1), dtype=np.float64)
    joint_rows = np.column_stack(
        (
            segment_times,
            sample_qpos[:, waist_columns],
            sample_qpos[:, left_columns],
            sample_qpos[:, right_columns],
            caps,
            heads,
            delays,
        )
    )

    base_id = int(model.body("base_link").id)
    waist_id = int(model.body("waist_yaw_link").id)
    left_wrist_id = int(model.body("left_wrist_yaw_link").id)
    right_wrist_id = int(model.body("right_wrist_yaw_link").id)
    left_tcp_id = ll.end_effector_site_id(model, "left")
    right_tcp_id = ll.end_effector_site_id(model, "right")
    eef = np.zeros((sample_times.size, 18), dtype=np.float64)
    tcp_audit = np.zeros((sample_times.size, 12), dtype=np.float64)
    model_qpos_names = [
        ll.mujoco.mj_id2name(model, ll.mujoco.mjtObj.mjOBJ_JOINT, joint_id)
        for joint_id in range(model.njnt)
    ]
    trajectory_by_name = {str(name): idx for idx, name in enumerate(names.tolist())}
    for frame in range(sample_times.size):
        for joint_id, joint_name in enumerate(model_qpos_names):
            if joint_name in trajectory_by_name:
                address = int(model.jnt_qposadr[joint_id])
                data.qpos[address] = sample_qpos[frame, trajectory_by_name[joint_name]]
        ll.mujoco.mj_forward(model, data)
        world_from_base = transform_from_body(data, base_id)
        base_from_world = np.linalg.inv(world_from_base)
        eef[frame, 0:6] = xyz_rpy(base_from_world @ transform_from_body(data, left_wrist_id))
        eef[frame, 6:12] = xyz_rpy(base_from_world @ transform_from_body(data, right_wrist_id))
        eef[frame, 12:18] = xyz_rpy(base_from_world @ transform_from_body(data, waist_id))
        tcp_audit[frame, 0:6] = xyz_rpy(base_from_world @ transform_from_site(data, left_tcp_id))
        tcp_audit[frame, 6:12] = xyz_rpy(base_from_world @ transform_from_site(data, right_tcp_id))

    # The SDK interpolates RPY components directly. Keep equivalent Euler angles
    # on a continuous branch so crossing +/-pi cannot command a nearly-2pi turn.
    for offset in (0, 6, 12):
        eef[:, offset + 3 : offset + 6] = np.unwrap(
            eef[:, offset + 3 : offset + 6], axis=0
        )
    for offset in (0, 6):
        tcp_audit[:, offset + 3 : offset + 6] = np.unwrap(
            tcp_audit[:, offset + 3 : offset + 6], axis=0
        )

    # Full 25-column EEF format: time, two wrist EEFs, waist EEF, caps, head attitude, delay.
    eef_heads = np.zeros((sample_times.size, 3), dtype=np.float64)
    eef_rows = np.column_stack((segment_times, eef, caps, eef_heads, delays))
    output = args.output_dir.resolve()
    joint_csv = output / "joint/action/1.csv"
    eef_csv = output / "eef/action/1.csv"
    write_csv(
        joint_csv,
        [
            "24 columns: send_time_s, waist_q x4, arm_q_l x7, arm_q_r x7, cap_l, cap_r, head_q x2, post_segment_delay_s",
            "SDK cap convention: 0=closed, 1=open. First row is an unvalidated transition from live state.",
        ],
        joint_rows,
    )
    write_csv(
        eef_csv,
        [
            "25 columns: send_time_s, ee_l x6, ee_r x6, ee_waist x6, cap_l, cap_r, head_att x3, post_segment_delay_s",
            "EEF arm poses are SDK controller wrist frames in base coordinates; R=Rz(yaw)Ry(pitch)Rx(roll).",
            "Controller-side IK can choose a different branch, so this EEF task is not collision-certified.",
        ],
        eef_rows,
    )
    write_yaml(output / "joint/yaml/config.yaml", "joint_interp")
    write_yaml(output / "eef/yaml/config.yaml", "eef_interp")
    np.savez_compressed(output / "tcp_fk_audit.npz", times_sec=sample_times, tcp_xyz_rpy_base=tcp_audit)

    min_joint_name = min(margins, key=margins.get)
    report = {
        "source_trajectory": str(trajectory_path),
        "source_sha256": sha256(trajectory_path),
        "config": str(args.config.resolve()),
        "sdk_reference": "user@192.168.3.27:/home/user/sdk (inspected 2026-09-01)",
        "frames": int(sample_times.size),
        "duration_sec": float(sample_times[-1] - sample_times[0]),
        "sdk_rate_hz": float(args.sdk_rate_hz),
        "initial_transition_sec": float(args.initial_transition_sec),
        "minimum_mink_clearance_m": float(np.min(mink_clearance)),
        "sdk_joint_limits_pass": True,
        "minimum_sdk_joint_margin": {
            "joint": min_joint_name,
            "rad": margins[min_joint_name],
            "deg": math.degrees(margins[min_joint_name]),
        },
        "all_sdk_joint_margins_rad": margins,
        "joint_csv": {"path": str(joint_csv), "rows": int(joint_rows.shape[0]), "columns": int(joint_rows.shape[1])},
        "eef_csv": {"path": str(eef_csv), "rows": int(eef_rows.shape[0]), "columns": int(eef_rows.shape[1])},
        "cap_conversion": "sdk_cap = 1 - simulation_gripper_position_command",
        "joint_export_status": "trajectory frames validated; first transition from live state is not collision-validated",
        "eef_export_status": "format/FK reference only; controller-side IK branch is not collision-validated",
        "hardware_release_blockers": [
            "verify live joint order/signs against one static status sample",
            "verify physical OmniPicker adapter/TCP calibration",
            "validate the live-state to first-frame transition in simulation",
            "perform reduced-speed dry run with hardware E-stop coverage",
        ],
    }
    report_path = output / "preflight_report.json"
    report_path.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(json.dumps(report, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()
